def gettext(text, *args, **kwargs):
    try:
        lang = session.get('lang', 'en')
    except RuntimeError:
        lang = 'en'
        
    translated = TRANSLATIONS.get(lang, {}).get(text, text)
    if kwargs:
        try:
            return translated.format(**kwargs)
        except Exception:
            return translated
    elif args:
        try:
            return translated.format(*args)
        except Exception:
            return translated
    return translated
